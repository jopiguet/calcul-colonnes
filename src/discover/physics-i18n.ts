const dictionaries: Record<Lang, Record<Key, string>> = { fr, es, en };

export type PhysicsKey = Key;

export function pt(key: Key, values: Record<string, string | number> = {}): string {
  return dictionaries[currentLang()][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

export const locale = (): string => ({ fr: "fr-CH", es: "es-ES", en: "en-GB" })[currentLang()];

/** A decimal in the interface's language, to `digits` places: "19,9", "19,9", "19.9". */
export function num(x: number, digits = 1): string {
  return new Intl.NumberFormat(locale(), { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(x);
}

/** A share as a percentage: "7,3 %", "7,3 %", "7.3%". */
export function pct(share: number, digits = 1): string {
  return new Intl.NumberFormat(locale(), { style: "percent", minimumFractionDigits: digits, maximumFractionDigits: digits }).format(share);
}

/** An angle: "45°". */
export const deg = (a: number): string => `${Math.round(a)}°`;

/** A list in the interface's language. */
export function andList(items: string[]): string {
  return new Intl.ListFormat(locale(), { style: "long", type: "conjunction" }).format(items);
}
