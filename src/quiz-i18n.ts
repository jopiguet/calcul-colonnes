const STATUS_KEYS: Record<SkillStatus, QuizKey> = {
  review: "statusReview",
  learning: "statusLearning",
  mastered: "statusMastered",
};

const dictionaries = { fr, es, en };

export function qt(key: QuizKey, values: Record<string, string | number> = {}): string {
  return dictionaries[currentLang()][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? ""),
  );
}

export const levelName = (level: Level): string => LEVEL_NAMES[currentLang()][level];
export const topicName = (topic: Topic): string => TOPIC_NAMES[currentLang()][topic];
export const promptText = (key: PromptKey): string => PROMPTS[currentLang()][key];
export const explanationText = (key: ExplanationKey): string => EXPLANATIONS[currentLang()][key];
export const skillName = (skill: string): string => SKILL_NAMES[currentLang()][skill] ?? skill;
export const statusName = (status: SkillStatus): string => qt(STATUS_KEYS[status]);
export const mistakeName = (mistake: string): string =>
  MISTAKE_NAMES[currentLang()][mistake as MistakeKey] ?? mistake;
export const skillNames = SKILL_NAMES;
