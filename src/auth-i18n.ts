const dictionaries = { fr, es, en };

export function at(key: AuthKey, values: Record<string, string | number> = {}): string {
  return dictionaries[currentLang()][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

/** Message for an error code from the API or from a provider redirect. */
export function errorText(code: string, values: Record<string, string> = {}): string {
  const key = `error.${code}` as AuthKey;
  return key in fr ? at(key, values) : at("error.unknown");
}
