-- Tests that bring back recent mistakes: the kinds of question reviewed are
-- part of what defines the test.
ALTER TABLE quiz_results ADD COLUMN focus TEXT NOT NULL DEFAULT '';  -- comma-separated question kinds
-- Generator version the test was made with; tests saved before this column are version 1.
ALTER TABLE quiz_results ADD COLUMN version INTEGER NOT NULL DEFAULT 1;

-- One row per answered question, filed under its kind ("derivatives.product"…):
-- this is what the progress page and the review of mistakes are built from.
CREATE TABLE quiz_answers (
  id       BIGINT   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id  BIGINT   NOT NULL REFERENCES quiz_results (id) ON DELETE CASCADE,
  user_id  BIGINT   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  at       BIGINT   NOT NULL,
  position INTEGER  NOT NULL,                 -- question number in the test, from 0
  skill    TEXT     NOT NULL,
  topic    TEXT     NOT NULL,
  given    INTEGER  NOT NULL,                 -- option chosen, -1 = blank
  correct  SMALLINT NOT NULL CHECK (correct IN (0, 1)),
  review   SMALLINT NOT NULL CHECK (review IN (0, 1))
);

CREATE INDEX quiz_answers_user_skill_at ON quiz_answers (user_id, skill, at);
CREATE INDEX quiz_answers_quiz_id ON quiz_answers (quiz_id);
